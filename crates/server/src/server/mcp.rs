//! MCP tools, mounted at `/mcp` (Streamable HTTP). They do what the routes do.

use std::sync::Arc;

use rmcp::handler::server::router::tool::ToolRouter;
use rmcp::handler::server::wrapper::Parameters;
use rmcp::model::{Implementation, ServerCapabilities, ServerConfig};
use rmcp::transport::streamable_http_server::{
    StreamableHttpServerConfig, StreamableHttpService, session::local::LocalSessionManager,
};
use rmcp::{ServerHandler, tool, tool_handler, tool_router};
use schemars::JsonSchema;
use serde::{Deserialize, Serialize};
use todo_client::{Id, NewTodo, Todo, TodoPatch};

use super::api_error::ApiError;
use crate::app::AppState;
use crate::config::mcp::McpConfig;

/// MCP over Streamable HTTP, ready for `Router::nest_service`.
///
/// Requests whose `Host` header is not in `[mcp] allowed_hosts` get a 403,
/// against DNS rebinding.
pub(super) fn service(
    state: AppState,
    config: &McpConfig,
) -> StreamableHttpService<Todos, LocalSessionManager> {
    let http = StreamableHttpServerConfig::default().with_allowed_hosts(&config.allowed_hosts);
    StreamableHttpService::new(move || Ok(Todos::new(state.clone())), Arc::default(), http)
}

/// What every tool returns: the todo(s) as JSON, or the error for the model.
type Answer = Result<String, String>;

/// Arguments of `list_todos`.
#[derive(Debug, Default, Deserialize, JsonSchema)]
#[schemars(transform = todo_core::nullable_any_of)]
pub(super) struct ListArgs {
    /// Also list done and cancelled todos.
    #[serde(default)]
    all: bool,
    /// Only todos whose text contains this, ignoring case.
    query: Option<String>,
    /// Only todos with this tag, without the `#`.
    tag: Option<String>,
}

impl ListArgs {
    /// `true` if `todo` passes every filter.
    fn keeps(&self, todo: &Todo) -> bool {
        (self.all || !todo.status.is_closed())
            && self
                .query
                .as_ref()
                .is_none_or(|query| todo.text.to_lowercase().contains(&query.to_lowercase()))
            && self
                .tag
                .as_ref()
                .is_none_or(|tag| todo.tags.iter().any(|t| t == tag.trim_start_matches('#')))
    }
}

/// Arguments of the tools that take only an id.
#[derive(Debug, Deserialize, JsonSchema)]
pub(super) struct IdArgs {
    /// The todo's id, e.g. `k3x9a2`.
    id: Id,
}

/// Arguments of `update_todo`.
#[derive(Debug, Deserialize, JsonSchema)]
#[schemars(transform = todo_core::nullable_any_of)]
pub(super) struct UpdateArgs {
    /// The todo's id, e.g. `k3x9a2`.
    id: Id,
    /// Fields to change.
    #[serde(flatten)]
    patch: TodoPatch,
}

/// The MCP server: the vault plus the tool table.
#[derive(Clone, Debug)]
pub(super) struct Todos {
    /// The vault.
    state: AppState,
    /// Generated by `#[tool_router]`.
    tool_router: ToolRouter<Self>,
}

#[tool_router]
impl Todos {
    /// Tools over `state`.
    fn new(state: AppState) -> Self {
        Self {
            state,
            tool_router: Self::tool_router(),
        }
    }

    /// Lists todos.
    #[tool(
        description = "List todos. Open ones only unless `all` is true; filter by text with `query` or by `tag`.",
        annotations(read_only_hint = true)
    )]
    async fn list_todos(&self, Parameters(args): Parameters<ListArgs>) -> Answer {
        json(
            &self
                .state
                .list_todos()
                .into_iter()
                .filter(|t| args.keeps(t))
                .collect::<Vec<_>>(),
        )
    }

    /// Adds a todo.
    #[tool(description = "Add a todo to the inbox note. Returns it with its new id.")]
    async fn add_todo(&self, Parameters(new): Parameters<NewTodo>) -> Answer {
        json(&self.state.add_todo(new).map_err(err)?)
    }

    /// Changes some fields.
    #[tool(
        description = "Change a todo. Only the fields given change; `due: null` clears the date.",
        annotations(idempotent_hint = true)
    )]
    async fn update_todo(&self, Parameters(args): Parameters<UpdateArgs>) -> Answer {
        json(&self.state.update_todo(&args.id, args.patch).map_err(err)?)
    }

    /// Ticks a todo.
    #[tool(description = "Mark a todo done.", annotations(idempotent_hint = true))]
    async fn complete_todo(&self, Parameters(args): Parameters<IdArgs>) -> Answer {
        json(&self.state.complete_todo(&args.id).map_err(err)?)
    }

    /// Removes a todo.
    #[tool(
        description = "Delete a todo and its line in the vault. Prefer complete_todo for finished work.",
        annotations(destructive_hint = true)
    )]
    async fn delete_todo(&self, Parameters(args): Parameters<IdArgs>) -> Answer {
        self.state.remove_todo(&args.id).map_err(err)?;
        Ok(format!("deleted {}", args.id.0))
    }
}

#[tool_handler(router = self.tool_router)]
impl ServerHandler for Todos {
    fn get_info(&self) -> ServerConfig {
        ServerConfig::new(ServerCapabilities::builder().enable_tools().build())
            .with_server_info(Implementation::new(
                env!("CARGO_PKG_NAME"),
                env!("CARGO_PKG_VERSION"),
            ))
            .with_instructions(
                "Personal todo list, stored as Obsidian Tasks lines in a vault. \
                 Call list_todos first to find ids.",
            )
    }
}

/// Pretty JSON, so the model reads it easily.
fn json<T: Serialize>(value: &T) -> Answer {
    serde_json::to_string_pretty(value).map_err(|e| e.to_string())
}

/// The route's error message as the tool's error text.
#[allow(clippy::needless_pass_by_value)] // used as `map_err(err)`
fn err(error: ApiError) -> String {
    error.message().to_owned()
}

#[cfg(test)]
mod tests {
    use axum::body::{Body, to_bytes};
    use axum::http::{Request, StatusCode, header};
    use axum::response::Response;
    use pretty_assertions::assert_eq;
    use todo_client::{Status, Todo};
    use tower::ServiceExt;

    use super::*;
    use crate::server::test_app;

    /// An open todo tagged `errand`.
    fn milk() -> Todo {
        Todo {
            id: Id("a1".into()),
            text: "Buy Milk".into(),
            status: Status::Todo,
            priority: todo_client::Priority::Normal,
            due: None,
            created: None,
            done: None,
            tags: vec!["errand".into()],
        }
    }

    #[test]
    fn list_filters() {
        let open = milk();
        let done = Todo {
            status: Status::Done,
            ..milk()
        };
        let args = |json: &str| serde_json::from_str::<ListArgs>(json).expect("json");

        assert!(args("{}").keeps(&open));
        assert!(!args("{}").keeps(&done));
        assert!(args(r#"{"all": true}"#).keeps(&done));
        assert!(args(r#"{"query": "milk"}"#).keeps(&open));
        assert!(!args(r#"{"query": "bread"}"#).keeps(&open));
        assert!(args(r##"{"tag": "#errand"}"##).keeps(&open));
        assert!(!args(r#"{"tag": "work"}"#).keeps(&open));
    }

    #[test]
    fn update_args_are_flat() {
        let args: UpdateArgs =
            serde_json::from_str(r#"{"id": "a1", "text": "x", "due": null}"#).expect("json");
        assert_eq!(args.id, Id("a1".into()));
        assert_eq!(args.patch.text.as_deref(), Some("x"));
        assert_eq!(args.patch.due, Some(None));
    }

    /// The tool's input schema, as rmcp builds it.
    fn schema<T: JsonSchema>() -> serde_json::Value {
        let generator = schemars::generate::SchemaSettings::draft2020_12().into_generator();
        generator.into_root_schema_for::<T>().to_value()
    }

    #[test]
    fn nullable_fields_use_any_of() {
        for schema in [
            schema::<ListArgs>(),
            schema::<NewTodo>(),
            schema::<UpdateArgs>(),
        ] {
            let text = schema.to_string();
            assert!(!text.contains(r#""type":["#), "{text}");
        }
        let due = &schema::<UpdateArgs>()["properties"]["due"];
        assert_eq!(due["anyOf"][0]["format"], "date", "{due}");
        assert_eq!(due["anyOf"][1]["type"], "null", "{due}");
    }

    /// POSTs a JSON-RPC message to `/mcp` with this `Host`.
    async fn post(app: &axum::Router, host: &str, body: &str) -> Response {
        let request = Request::post("/mcp")
            .header(header::HOST, host)
            .header(header::CONTENT_TYPE, "application/json")
            .header(header::ACCEPT, "application/json, text/event-stream")
            .body(Body::from(body.to_owned()))
            .expect("valid request");
        app.clone().oneshot(request).await.expect("infallible")
    }

    /// The `initialize` request every client sends first.
    const INIT: &str = r#"{"jsonrpc":"2.0","id":1,"method":"initialize","params":{"protocolVersion":"2025-06-18","capabilities":{},"clientInfo":{"name":"test","version":"0"}}}"#;

    #[tokio::test]
    async fn mounted_at_mcp() {
        let (_dir, app) = test_app("# Todo\n- [ ] a ^aaaaaa\n");
        let response = post(&app, "localhost", INIT).await;
        assert_eq!(response.status(), StatusCode::OK);
        let bytes = to_bytes(response.into_body(), usize::MAX)
            .await
            .expect("body");
        let body = String::from_utf8_lossy(&bytes);
        assert!(body.contains(env!("CARGO_PKG_NAME")), "{body}");
    }

    #[tokio::test]
    async fn refuses_unknown_hosts() {
        let (_dir, app) = test_app("");
        let response = post(&app, "evil.example.com", INIT).await;
        assert_eq!(response.status(), StatusCode::FORBIDDEN);
    }
}
